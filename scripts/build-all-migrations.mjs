/**
 * Concatenates every migration, in order, into supabase/ALL_MIGRATIONS.sql.
 *
 * Why: the migrations have ordering dependencies -- 000009 references a table
 * created by 000006 -- and running them by hand in the wrong order fails with a
 * missing-relation error that gives no hint about the cause. That happened once
 * already.
 *
 * Every migration is written to be idempotent, so re-running the combined file
 * is safe: it confirms the current state rather than duplicating anything.
 *
 *   node scripts/build-all-migrations.mjs
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'supabase', 'migrations');
const out = join(root, 'supabase', 'ALL_MIGRATIONS.sql');

const files = readdirSync(dir)
    .filter((f) => f.endsWith('.sql'))
    .sort();

if (files.length === 0) {
    console.error('No migrations found.');
    process.exit(1);
}

const header = `-- ============================================================================
-- Nefer Kali Healing -- all migrations, in order
-- ============================================================================
-- Run this ONCE in the Supabase SQL Editor. Every statement is idempotent, so
-- running it again is safe and will simply confirm the current state.
--
-- WHY THIS FILE EXISTS: the individual migrations have ordering dependencies
-- (000009 references a table created by 000006), and running them by hand in the
-- wrong order fails with a confusing missing-relation error. This file removes
-- that hazard.
--
-- Generated by: node scripts/build-all-migrations.mjs
-- ============================================================================


`;

const body = files
    .map((name) => {
        const sep = '#'.repeat(76);
        return [
            `-- ${sep}`,
            `-- # ${name}`,
            `-- ${sep}`,
            '',
            readFileSync(join(dir, name), 'utf8').trimEnd(),
            '',
        ].join('\n');
    })
    .join('\n');

writeFileSync(out, header + body, 'utf8');

const lines = (header + body).split('\n').length;
console.log(`Wrote supabase/ALL_MIGRATIONS.sql`);
console.log(`  ${files.length} migrations, ${lines} lines`);
for (const f of files) console.log(`    ${f}`);
